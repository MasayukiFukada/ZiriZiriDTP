def crc8(data):
    c = 0
    for b in data:
        c = CRC8_TABLE[(c ^ b) & 0xff]
    return c

def cat_packet(cmd, payload=b""):
    length = len(payload)
    c = crc8(payload)
    return bytes([0x51, 0x78, cmd, 0x00, length, 0x00, c]) + payload + bytes([0xff])

def notify_cb(sender, data):
    print(f"  [NOTIFY] {data.hex()}")

async def main():
    print(f"Scanning for {ADDRESS}...")
    device = await BleakScanner.find_device_by_address(ADDRESS, timeout=10.0)
    if not device:
        print("Device not found during scan. Trying direct address connect...")
        target = ADDRESS
    else:
        print(f"Found device: {device.name} ({device.address})")
        target = device

    async with BleakClient(target, timeout=15.0) as client:
        print(f"Connected! MTU: {client.mtu_size}")

        for n_uuid in [NOTIFY_FFE2, NOTIFY_FF14]:
            try:
                await client.start_notify(n_uuid, notify_cb)
                print(f"Subscribed to {n_uuid}")
            except Exception as e:
                print(f"Could not subscribe to {n_uuid}: {e}")

        # Send feed packets
        feed_pkt_a1 = cat_packet(0xa1, bytes([0x50, 0x00])) # 80 lines feed
        feed_pkt_a3 = cat_packet(0xa3, bytes([0x50, 0x00]))
        esc_feed = b"\x1b@\n\n\n\n\x1bd\x05"

        for w_name, w_uuid in [("ffe1", WRITE_FFE1), ("ff15", WRITE_FF15)]:
            print(f"\n--- Testing write to {w_name} ---")
            print("Sending Cat 0xA1 Feed...")
            await client.write_gatt_char(w_uuid, feed_pkt_a1, response=False)
            await asyncio.sleep(1.5)
            
            print("Sending Cat 0xA3 Feed...")
            await client.write_gatt_char(w_uuid, feed_pkt_a3, response=False)
            await asyncio.sleep(1.5)

            print("Sending ESC/POS Feed...")
            await client.write_gatt_char(w_uuid, esc_feed, response=False)
            await asyncio.sleep(1.5)

        print("\nDone. Waiting 2s...")
        await asyncio.sleep(2.0)

if __name__ == "__main__":
    asyncio.run(main())
